#!/usr/bin/env bash
# scripts/update-model-manifest.sh
# Downloads upstream sherpa-onnx model archives, verifies SHA-256 and byte sizes,
# and generates assets/models.toml.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
MANIFEST_FILE="${REPO_ROOT}/assets/models.toml"
mkdir -p "${REPO_ROOT}/target/tmp"
TMP_DIR="$(mktemp -d -p "${REPO_ROOT}/target/tmp" -t speechyyy-manifest-XXXXXX)"

trap 'rm -rf "${TMP_DIR}"' EXIT

mkdir -p "${REPO_ROOT}/assets"

MODELS=(
    "parakeet-tdt-v3|https://github.com/k2-fsa/sherpa-onnx/releases/download/asr-models/sherpa-onnx-nemo-parakeet-tdt-0.6b-v3-int8.tar.bz2|CC-BY-4.0|https://huggingface.co/nvidia/parakeet-tdt-0.6b-v3|NVIDIA NeMo Parakeet-TDT-0.6b-v3 (0.6B INT8), quantized by k2-fsa/sherpa-onnx|encoder.int8.onnx,decoder.int8.onnx,joiner.int8.onnx,tokens.txt"
    "whisper-small|https://github.com/k2-fsa/sherpa-onnx/releases/download/asr-models/sherpa-onnx-whisper-small.tar.bz2|MIT|https://github.com/openai/whisper/blob/main/LICENSE|OpenAI Whisper Small (INT8), converted and quantized by k2-fsa/sherpa-onnx|encoder.int8.onnx,decoder.int8.onnx,tokens.txt"
    "whisper-large-v3-turbo|https://github.com/k2-fsa/sherpa-onnx/releases/download/asr-models/sherpa-onnx-whisper-turbo.tar.bz2|MIT|https://github.com/openai/whisper/blob/main/LICENSE|OpenAI Whisper Large-v3-Turbo (INT8), converted and quantized by k2-fsa/sherpa-onnx|encoder.int8.onnx,decoder.int8.onnx,tokens.txt"
    "moonshine-base|https://github.com/k2-fsa/sherpa-onnx/releases/download/asr-models/sherpa-onnx-moonshine-base-en-int8.tar.bz2|MIT|https://github.com/usefulsensors/moonshine/blob/main/LICENSE|Useful Sensors Moonshine Base (INT8), converted and quantized by k2-fsa/sherpa-onnx|preprocess.onnx,encode.int8.onnx,uncached_decode.int8.onnx,cached_decode.int8.onnx,tokens.txt"
)

echo "# Generated by scripts/update-model-manifest.sh at $(date -u +%Y-%m-%dT%H:%M:%SZ)" > "${MANIFEST_FILE}"
echo "# Pinned model specifications for Speechyyy local offline models." >> "${MANIFEST_FILE}"
echo "" >> "${MANIFEST_FILE}"

for item in "${MODELS[@]}"; do
    IFS="|" read -r id url license license_url attribution expected_str <<< "${item}"
    echo "Processing ${id}..."
    archive_path="${TMP_DIR}/${id}.tar.bz2"

    sha256=""
    size_bytes=0
    max_extracted_bytes=0
    max_files=0

    # Attempt download if network is available
    if curl --version >/dev/null 2>&1 && curl -s --connect-timeout 5 -I "https://github.com" >/dev/null 2>&1; then
        echo "  Downloading archive from ${url}..."
        curl -fSL --retry 2 --retry-delay 2 -o "${archive_path}" "${url}"
        size_bytes=$(stat -c%s "${archive_path}")
        sha256=$(sha256sum "${archive_path}" | awk '{print $1}')

        echo "  Confirming checksum with second stream verification..."
        verify_sha256=$(curl -fSL --retry 2 -s "${url}" | sha256sum | awk '{print $1}')
        if [ "${sha256}" != "${verify_sha256}" ]; then
            echo "ERROR: Checksum mismatch between downloads for ${id}! First: ${sha256}, Second: ${verify_sha256}" >&2
            exit 1
        fi

        echo "  Analyzing archive contents..."
        extract_dir="${TMP_DIR}/extract_${id}"
        mkdir -p "${extract_dir}"
        tar -xjf "${archive_path}" -C "${extract_dir}"

        real_files=$(find "${extract_dir}" -type f | wc -l)
        real_extracted_bytes=$(find "${extract_dir}" -type f -exec stat -c%s {} + | awk '{s+=$1} END {print s}')

        # Add modest margins (20% or 30MB)
        max_files=$(( real_files + 5 ))
        margin=$(( real_extracted_bytes / 5 ))
        if [ "${margin}" -lt 30000000 ]; then
            margin=30000000
        fi
        max_extracted_bytes=$(( real_extracted_bytes + margin ))
        echo "  ${id}: sha256=${sha256}, size=${size_bytes}, max_files=${max_files}, max_extracted_bytes=${max_extracted_bytes}"
        rm -rf "${extract_dir}" "${archive_path}"
    else
        echo "  Network unavailable; leaving sha256 empty for fail-closed verification."
    fi

    # Format expected files array for TOML
    IFS="," read -r -a exp_arr <<< "${expected_str}"
    exp_toml="["
    for idx in "${!exp_arr[@]}"; do
        if [ "${idx}" -gt 0 ]; then
            exp_toml="${exp_toml}, "
        fi
        exp_toml="${exp_toml}\"${exp_arr[$idx]}\""
    done
    exp_toml="${exp_toml}]"

    cat >> "${MANIFEST_FILE}" <<EOF
[models.${id}]
id = "${id}"
url = "${url}"
sha256 = "${sha256}"
size_bytes = ${size_bytes}
max_extracted_bytes = ${max_extracted_bytes}
max_files = ${max_files}
expected_files = ${exp_toml}
license = "${license}"
license_url = "${license_url}"
attribution = "${attribution}"

EOF
done

echo "Manifest successfully written to ${MANIFEST_FILE}"
